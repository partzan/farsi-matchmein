export function groupFa(name: string | undefined): string {
  if (!name) return 'سایر';
  return GROUP_FA[name] ?? name;
}

export function categoryFa(name: string | undefined): string {
  if (!name) return '';
  const canonical = canonicalCategoryName(name);
  return CATEGORY_FA[canonical] ?? CATEGORY_FA[name] ?? (canonical || name);
}
